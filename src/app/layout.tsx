import type { Metadata } from "next";
import { GeistMono } from "geist/font/mono";
import { GeistSans } from "geist/font/sans";
import { Instrument_Sans } from "next/font/google";
import Navbar from "@/components/Navbar";
import { getNavFeature } from "@/lib/resources";
import "./globals.css";

// The site's one typeface: headings and body. Variable, with the width axis.
const instrument = Instrument_Sans({
  variable: "--font-instrument",
  subsets: ["latin"],
  axes: ["wdth"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({ children }: LayoutProps<"/">) {
  // The Resources menu's featured card comes from the CMS, so it's fetched here and handed to the client nav.
  const resourcesFeature = await getNavFeature();
  return (
    <html
      lang="en"
      className={`${instrument.variable} ${GeistSans.variable} ${GeistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">
        <Navbar resourcesFeature={resourcesFeature} />
        {children}
      </body>
    </html>
  );
}
