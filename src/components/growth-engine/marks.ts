export type Mark = keyof typeof MARKS;

/**
 * How each mark is drawn in its real brand colors on a round white badge:
 * `color` fills the path (its cut-outs show the white badge), `fit` is
 * its width as a share of the badge. Google has no single color, so it is
 * painted in its four brand colors (see `paintMark`).
 */
export const MARK_STYLE: Record<Mark, { color: string; fit: number }> = {
  hackernews: { color: "#ff6600", fit: 0.6 },
  google: { color: "#4285f4", fit: 0.66 },
  chatgpt: { color: "#0d0d0d", fit: 0.66 },
  reddit: { color: "#ff4500", fit: 0.8 },
  youtube: { color: "#ff0000", fit: 0.76 },
};

// Google's G in four colors: wedges around the center (canvas angles, y down), blue also takes the crossbar.
const GOOGLE_WEDGES: [string, number, number][] = [
  ["#ea4335", 200, 325], // red, top
  ["#fbbc05", 145, 200], // yellow, left
  ["#34a853", 40, 145], // green, bottom
  ["#4285f4", -35, 40], // blue, right
];

/** Paints a mark in its brand colors into a 24×24 box already mapped onto the canvas. */
export function paintMark(ctx: CanvasRenderingContext2D, mark: Mark) {
  const path = new Path2D(MARKS[mark]);
  if (mark !== "google") {
    ctx.fillStyle = MARK_STYLE[mark].color;
    ctx.fill(path);
    return;
  }
  ctx.save();
  ctx.clip(path);
  for (const [color, from, to] of GOOGLE_WEDGES) {
    ctx.fillStyle = color;
    ctx.beginPath();
    ctx.moveTo(12, 12);
    ctx.arc(12, 12, 14, (from * Math.PI) / 180, (to * Math.PI) / 180);
    ctx.closePath();
    ctx.fill();
  }
  ctx.fillStyle = "#4285f4";
  ctx.fillRect(12, 9.5, 12, 5); // crossbar
  ctx.restore();
}

/** White round badge with the mark at its brand size (moved from Destinations' Puck). */
export function paintBadge(ctx: CanvasRenderingContext2D, w: number, h: number, mark: Mark) {
  ctx.fillStyle = "#ffffff";
  ctx.beginPath();
  ctx.arc(w / 2, h / 2, w / 2, 0, Math.PI * 2);
  ctx.fill();
  const s = (w * MARK_STYLE[mark].fit) / 24;
  ctx.save(); // repaints reuse the context, so don't let the transform stack up
  ctx.translate(w / 2 - 12 * s, h / 2 - 12 * s);
  ctx.scale(s, s);
  paintMark(ctx, mark);
  ctx.restore();
}
